#!/usr/bin/env node
// Lesehilfe native messaging host. Chrome starts this when the side panel connects
// and stops it when the panel closes.
//
// Requests:  { id, method, params }
// Responses: { id, result } | { id, error }
// Events:    { id, event, data }   (progress for a pending request)
import { searchTools } from './env.js'; // must come first: sets up pi's environment
import { log, onMessage, send } from './native.js';
import fs from 'node:fs';
import { ensurePR, preparePR, cleanupWorktrees, gitVersion, worktreePath } from './repo.js';
import * as tour from './tour.js';
import * as agent from './agent.js';

const VERSION = '0.7.0';

const methods = {
  async status() {
    return {
      version: VERSION,
      node: process.version,
      pi: agent.PI_VERSION,
      git: await gitVersion(),
      tools: searchTools(),
      codex: agent.codexStatus(),
    };
  },

  codexLogin({ method = 'browser' }, emit) {
    return agent.codexLogin(method, (step) => emit('codexLogin', step));
  },
  codexLoginCancel: () => agent.codexLoginCancel(),
  codexLogout: () => agent.codexLogout(),

  async prepare(params, emit) {
    return preparePR(params, (message) => emit('progress', { message }));
  },

  // Past conversation for a PR, without cloning anything if it was never prepared.
  async history({ owner, repo, number, model }) {
    const path = worktreePath(owner, repo, number);
    return fs.existsSync(path) ? agent.history(path, model || agent.DEFAULT_MODEL) : [];
  },

  async ask(params, emit) {
    const { path, sha } = await preparePR(params, (message) => emit('progress', { message }));
    emit('progress', { message: null });
    await agent.ask(path, params.model || agent.DEFAULT_MODEL, params.message, (data) => emit('agent', data), {
      fresh: params.fresh,
    });
    return { sha };
  },

  async abort({ owner, repo, number, kind }) {
    await agent.abort(worktreePath(owner, repo, number), kind);
  },

  // Stored user-flow overview for a PR, or null.
  overview({ owner, repo, number }) {
    return agent.loadOverview(worktreePath(owner, repo, number));
  },

  // --- Tours ---
  async stopExcerpt(params, emit) {
    const { path } = await ensurePR(params, (message) => emit('progress', { message }));
    return tour.excerpt(path, params.stop);
  },

  async stopDiff(params, emit) {
    const { path } = await ensurePR(params, (message) => emit('progress', { message }));
    return tour.stopDiff(path, params.stop);
  },

  // Sub-stops for a stop, from cache or generated by the agent. `key` = "<flow>/<step>/…".
  async deepen(params, emit) {
    const { path } = await ensurePR(params, (message) => emit('progress', { message }));
    const overview = agent.loadOverview(path);
    const flow = overview?.flows[params.flowIndex];
    if (!flow) throw new Error('Run Familiarize first.');
    const cached = tour.loadTours(path, overview.createdAt)[params.key];
    if (cached && !params.regenerate) return cached;
    emit('progress', { message: null });
    const stops = await agent.deepen(path, params.model || agent.DEFAULT_MODEL, { flow, trail: params.trail }, (data) =>
      emit('agent', data)
    );
    tour.saveSubStops(path, overview.createdAt, params.key, stops);
    return stops;
  },

  // Storyboards already saved for a flow ({ [index]: storyboard }); no git, no agent.
  cachedStoryboards({ owner, repo, number, flowIndex }) {
    const path = worktreePath(owner, repo, number);
    const overview = agent.loadOverview(path);
    if (!overview?.flows[flowIndex]) return {};
    const cached = tour.loadTours(path, overview.createdAt);
    const result = {};
    overview.flows[flowIndex].steps.forEach((_, i) => {
      const hit = cached[`sb:${flowIndex}:${i}`];
      if (hit && !Array.isArray(hit) && hit.arrival?.how != null) result[i] = hit;
    });
    return result;
  },

  // Storyboards for the on-page tour of one flow: cached ones first, then the agent writes the
  // missing ones; each arrives as a 'storyboard' event ({ index, beats }) as soon as it exists.
  async storyboards(params, emit) {
    const { path } = await ensurePR(params, (message) => emit('progress', { message }));
    const overview = agent.loadOverview(path);
    const flow = overview?.flows[params.flowIndex];
    if (!flow) throw new Error('Run Familiarize first.');
    const cached = tour.loadTours(path, overview.createdAt);
    const key = (i) => `sb:${params.flowIndex}:${i}`;
    const missing = [];
    flow.steps.forEach((_, i) => {
      // Storyboards from earlier versions (plain beat arrays, no runsIn) are rewritten.
      const hit = cached[key(i)];
      if (hit && !Array.isArray(hit) && hit.runsIn && hit.arrival?.how != null && !params.regenerate) emit('storyboard', { index: i, storyboard: hit });
      else missing.push(i);
    });
    if (!missing.length) return { missing: [] };
    emit('progress', { message: null });
    const left = await agent.storyboards(
      path,
      params.model || agent.DEFAULT_MODEL,
      { flow, stops: flow.steps, only: missing },
      (index, storyboard) => tour.validateStoryboard(path, flow.steps, index, storyboard),
      (index, storyboard) => {
        tour.saveTourEntry(path, overview.createdAt, key(index), storyboard);
        emit('storyboard', { index, storyboard });
      },
      (data) => emit('agent', data)
    );
    return { missing: left };
  },

  // Next level of detail for a beat of the on-page tour (cached per frame, beat and level).
  async zoom(params, emit) {
    const { path } = await ensurePR(params, (message) => emit('progress', { message }));
    const overview = agent.loadOverview(path);
    const flow = overview?.flows[params.flowIndex];
    const stop = flow?.steps[params.stopIndex];
    if (!stop) throw new Error('Run Familiarize first.');
    const key = `zoom:${params.flowIndex}:${params.frameKey}:${params.beatIndex}:${params.history.length + 2}`;
    const cached = tour.loadTours(path, overview.createdAt)[key];
    if (cached && !params.regenerate) return cached;
    emit('progress', { message: null });
    const result = await agent.zoom(
      path,
      params.model || agent.DEFAULT_MODEL,
      { flow, stop, frame: params.frame, beat: params.beat, history: params.history },
      (report) => tour.validateZoom(path, params.frame, params.beat, report),
      (data) => emit('agent', data)
    );
    tour.saveTourEntry(path, overview.createdAt, key, result);
    return result;
  },

  // Cached sub-stops for every stop of an overview, so the panel can show them without asking.
  tours({ owner, repo, number }) {
    const path = worktreePath(owner, repo, number);
    const overview = agent.loadOverview(path);
    return overview ? tour.loadTours(path, overview.createdAt) : {};
  },

  async familiarize(params, emit) {
    if (!params.base) throw new Error('Base branch unknown — is the PR context loaded?');
    const { path, sha, baseSha } = await preparePR(params, (message) => emit('progress', { message }));
    emit('progress', { message: null });
    return agent.familiarize(path, params.model || agent.DEFAULT_MODEL, { sha, baseSha, pr: params.pr || {} }, (data) =>
      emit('agent', data)
    );
  },
};

onMessage(async ({ id, method, params = {} }) => {
  const emit = (event, data) => send({ id, event, data });
  try {
    if (!methods[method]) throw new Error(`Unknown method ${method}`);
    const result = await methods[method](params, emit);
    send({ id, result: result ?? null });
  } catch (e) {
    log(`${method} failed`, e);
    send({ id, error: e.message });
  }
});

process.stdin.on('end', () => process.exit(0));
process.on('uncaughtException', (e) => log('uncaught', e));
process.on('unhandledRejection', (e) => log('unhandled', e));

log(`helper ${VERSION} started (node ${process.version})`);
cleanupWorktrees().catch((e) => log('cleanup failed', e));
